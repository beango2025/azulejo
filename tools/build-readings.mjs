import fs from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const contentDir = path.join(root, 'content');
const briefs = JSON.parse(fs.readFileSync(path.join(contentDir, 'lesson-briefs.json'), 'utf8'));
const expected = new Map(briefs.map(item => [item.id, item]));
const targets = {
  A1: [140, 180],
  A2: [180, 230],
  B1: [280, 340],
  B2: [420, 500],
  C1: [550, 650],
  C2: [700, 850]
};

const files = fs.readdirSync(contentDir)
  .filter(name => /^readings-[A-Z0-9]+-\d+\.json$/.test(name))
  .sort();
const entries = [];
for (const file of files) {
  const data = JSON.parse(fs.readFileSync(path.join(contentDir, file), 'utf8'));
  if (!Array.isArray(data)) throw new Error(`${file}: expected an array`);
  for (const entry of data) entries.push({ ...entry, __file: file });
}

const seen = new Set();
const problems = [];
const merged = {};
for (const entry of entries) {
  const brief = expected.get(entry.id);
  if (!brief) { problems.push(`unknown id ${entry.id}`); continue; }
  if (seen.has(entry.id)) { problems.push(`duplicate id ${entry.id}`); continue; }
  seen.add(entry.id);
  const words = String(entry.text || '').trim().split(/\s+/).filter(Boolean).length;
  const [min, max] = targets[brief.level];
  if (words < min || words > max) problems.push(`${entry.id} ${brief.level}: ${words} words (target ${min}-${max})`);
  if (!Array.isArray(entry.questions) || entry.questions.length !== 4) problems.push(`${entry.id}: need 4 questions`);
  (entry.questions || []).forEach((q, i) => {
    if (!Array.isArray(q.options) || q.options.length !== 3) problems.push(`${entry.id} q${i + 1}: need 3 options`);
    if (!q.options || !q.options.includes(q.answer)) problems.push(`${entry.id} q${i + 1}: answer not in options`);
  });
  merged[entry.id] = { id: entry.id, title: entry.title || brief.title, text: entry.text, questions: entry.questions };
}
for (const brief of briefs) {
  if (!seen.has(brief.id)) problems.push(`missing ${brief.id}`);
}

fs.writeFileSync(path.join(root, 'js', 'readings.js'), `/* Azulejo — exam-length reading library (generated by tools/build-readings.mjs). */\nwindow.AZ_READINGS = ${JSON.stringify(merged, null, 2)};\n`, 'utf8');
console.log(`files=${files.length} entries=${entries.length} merged=${Object.keys(merged).length} problems=${problems.length}`);
if (problems.length) console.log(problems.join('\n'));
